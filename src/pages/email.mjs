// Sign-in code email for Supabase Auth (Authentication → Emails → Templates).
// Built from the approved Gold listings, so re-run the build and paste it again when
// the Gold list changes. Email clients ignore <style> and gradients, so everything is
// inline and laid out with tables. {{ .Token }} and {{ .ConfirmationURL }} are filled
// in by Supabase.
import { esc, SITE } from '../lib.mjs';

const O = SITE.origin;
const abs = p => (/^https?:/.test(p) ? p : O + p);
const F = "font-family:'Segoe UI',Helvetica,Arial,sans-serif";

// Proudly South African ribbon, one cell per flag colour (Outlook drops gradients).
const ribbon = () => `<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"><tr>${
  ['#007749', '#FFB81C', '#E03C31', '#001489', '#000000'].map(c => `<td height="4" style="height:4px;line-height:4px;font-size:0;background:${c}">&nbsp;</td>`).join('')}</tr></table>`;

function goldAd(b) {
  const url = `${O}/b/${encodeURIComponent(b.slug)}/?ref=email`;
  const mark = b.logo
    ? `<img src="${esc(abs(b.logo))}" width="48" height="48" alt="" style="display:block;width:48px;height:48px;border-radius:12px;border:0">`
    : `<table role="presentation" cellpadding="0" cellspacing="0" border="0"><tr><td width="48" height="48" align="center" style="width:48px;height:48px;border-radius:12px;background:#0B2A6F;color:#FFB81C;${F};font-size:20px;font-weight:700">${esc((b.name || '?').trim().charAt(0).toUpperCase())}</td></tr></table>`;
  const where = [b.category_name, b.city_name].filter(Boolean).map(esc).join(' &middot; ');
  return `<tr><td style="padding:0 0 10px">
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="background:#FFFFFF;border:1px solid #F0DDB0;border-radius:12px">
    <tr><td style="padding:14px">
      <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0"><tr>
        <td width="48" valign="top" style="width:48px"><a href="${url}" style="text-decoration:none">${mark}</a></td>
        <td valign="top" style="padding-left:12px;${F}">
          <a href="${url}" style="color:#071A47;text-decoration:none;font-size:15px;font-weight:700">${esc(b.name)}</a>
          <img src="${O}/assets/seal-gold.png" width="15" height="15" alt="Gold Verified" style="width:15px;height:15px;vertical-align:-2px;border:0;margin-left:3px">
          ${where ? `<div style="color:#5B6B8C;font-size:12px;padding-top:2px">${where}</div>` : ''}
          ${b.tagline ? `<div style="color:#33405F;font-size:13px;line-height:1.45;padding-top:6px">${esc(b.tagline)}</div>` : ''}
          <div style="padding-top:10px"><a href="${url}" style="display:inline-block;${F};font-size:12px;font-weight:700;color:#071A47;background:#FFB81C;border-radius:999px;padding:7px 14px;text-decoration:none">View profile &rarr;</a></div>
        </td>
      </tr></table>
    </td></tr>
  </table>
</td></tr>`;
}

